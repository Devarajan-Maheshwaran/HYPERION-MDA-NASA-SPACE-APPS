"""Render experiments/m6/outputs/report.md from results.json only (no other inputs).

Every number in the report is read from results.json; `verify_m6.py` re-renders
the report and checks it is byte-identical, and recomputes results.json metrics
from the raw prediction CSVs.
"""

from __future__ import annotations

HR_MODEL_NAMES = {
    "A0": "Training-mean predictor (no signal)",
    "A1": "M5 peak-interval method (frozen, untuned)",
    "A2": "PPG spectral peak (untrained)",
    "A3": "Ridge, PPG features",
    "A4": "Ridge, PPG + accelerometer features",
    "A5": "Ridge, accelerometer features only (ablation)",
}
ACT_MODEL_NAMES = {"B0": "Majority class", "B1": "Logistic, accelerometer features",
                   "B2": "Logistic, accelerometer + PPG features"}


def f(x, d=2):
    return "n/a" if x is None else f"{x:.{d}f}"


def pct(x):
    return "n/a" if x is None else f"{100 * x:.1f}%"


def ci(a, d=2):
    return f"{f(a['mean'], d)} [{f(a['ci_low'], d)}, {f(a['ci_high'], d)}]"


def table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def hr_section(block, title, participants):
    m = block["models"]
    lines = [f"### {title}", "",
             f"Scored windows: {block['n_windows']} (common to all models: {block['n_common_windows']}).", "",
             "**Aggregate over participants** (unweighted mean of per-participant values; 95% participant-bootstrap interval in brackets):", ""]
    rows = []
    for k, mod in m.items():
        a = mod["aggregate"]
        rows.append([k, HR_MODEL_NAMES[k], ci(a["mae"]), f"{f(a['mae']['median'])} ({f(a['mae']['min'])}–{f(a['mae']['max'])})",
                     ci(a["rmse"]), f(a["bias"]["mean"]), pct(mod["coverage"]),
                     f(mod["pooled_windows"]["mae"]), f(mod["pooled_windows"]["rmse"])])
    lines += [table(["ID", "Model", "MAE bpm", "MAE median (range)", "RMSE bpm", "Mean bias", "Coverage",
                     "Pooled-window MAE", "Pooled-window RMSE"], rows), ""]
    lines += ["**Per-participant MAE (bpm)**", "",
              table(["Model", *participants], [[k, *[f(mod["per_participant"][p]["mae"]) for p in participants]] for k, mod in m.items()]), ""]
    lines += ["**Per-participant RMSE (bpm)**", "",
              table(["Model", *participants], [[k, *[f(mod["per_participant"][p]["rmse"]) for p in participants]] for k, mod in m.items()]), ""]
    lines += ["**Per-participant bias (estimate − reference, bpm)**", "",
              table(["Model", *participants], [[k, *[f(mod["per_participant"][p]["bias"]) for p in participants]] for k, mod in m.items()]), ""]
    lines += ["**Per-participant A1 coverage** (fraction of eligible windows where the frozen M5 method produced an estimate)", "",
              table(participants, [[pct(m["A1"]["per_participant"][p]["coverage"]) for p in participants]]), ""]
    lines += ["**Common windows only** (windows where every model, including A1, produced an estimate):", "",
              table(["Model", "MAE bpm [95% CI]"], [[k, ci(mod["common_windows"]["aggregate_mae"])] for k, mod in m.items()]), ""]
    lines += ["**S3: aggregate without participant s4** (models unchanged):", "",
              table(["Model", "MAE bpm [95% CI]", "RMSE bpm [95% CI]"],
                    [[k, ci(mod["aggregate_without_s4"]["mae"]), ci(mod["aggregate_without_s4"]["rmse"])] for k, mod in m.items()]), ""]
    return lines


def render(r: dict) -> str:
    dc, prov = r["dataset_check"], r["provenance"]
    participants = dc["participants"]
    L = [f"# {r['title']}", "",
         "> **RECORDED-NON-ASTRONAUT METHODS DEMONSTRATION. NOT VALIDATED.** 8 adults, terrestrial laboratory exercise "
         "(treadmill walk/run, exercise bike). These are measurements of simple baselines on this dataset only. They make no "
         "claim about astronauts, spaceflight, clinical use or device performance. Activity labels are per-record protocol labels.", "",
         "Generated by `experiments/m6/run_m6.py` from the frozen `experiments/m6/m6-lopo-config.json`. "
         "Protocol: `docs/M6-LOPO-PROTOCOL.md`. Every number below is read from `results.json`.", "",
         "## 1. Reproducibility", "",
         table(["Item", "Value"], [
             ["Config", f"{prov['config_file']} ({prov['config_version']})"],
             ["Config SHA-256", f"`{prov['config_sha256']}`"],
             ["Dataset manifest SHA-256", f"`{prov['dataset_manifest_sha256']}`"],
             ["Git HEAD", f"`{prov['git_head']}` ({prov['git_note']})"],
             ["Python / numpy / scipy", f"{prov['python']} / {prov['numpy']} / {prov['scipy']}"],
             ["Bootstrap seed", prov["random_seed_bootstrap"]],
             ["Hyperparameters", "fixed, pre-declared (ridge α = 1.0, logistic C = 1.0); no tuning"]]), "",
         "Source file hashes are listed in `results.json` → `provenance.source_sha256`.", "",
         "## 2. Dataset check", "",
         f"{dc['n_records']} records, {len(participants)} participants ({', '.join(participants)}), "
         f"{dc['n_windows']} windows of 8 s (2 s step), {dc['n_hr_eligible_windows']} with ≥ 3 reference beats. "
         f"Degenerate (flat-spectrum) feature windows: {dc['degenerate_feature_windows']}.", "",
         f"**Frozen-method check:** A1 per-window errors are identical to M5 `dsp_hr.check_record` for "
         f"{dc['a1_matches_m5_dsp_hr']['records_checked']} of 19 records "
         f"(all identical: {dc['a1_matches_m5_dsp_hr']['all_identical']}).", ""]
    L.append(table(["Record", "Header comment", "Duration s", "Windows", "HR-eligible", "No reference", "Fail RR screen (S2)"],
                   [[k, v["header_comment"], f(v["duration_s"], 0), v["windows"], v["hr_eligible_windows"],
                     v["windows_without_reference"], v["eligible_windows_failing_rr_screen"]] for k, v in dc["per_record"].items()]))
    L += ["", f"**S1 (exercise-onset sensitivity): {r['sensitivity']['S1']['status'].upper()}.** {r['sensitivity']['S1']['reason']}", "",
          "## 3. Heart-rate estimation (Task A)", "",
          "Reference: 60 / median RR of the hand-marked chest-ECG R peaks in each window. ECG is never a model input. "
          "Errors are estimate − reference.", ""]
    L += hr_section(r["hr"]["primary"], "3.1 Primary analysis (all eligible windows)", participants)
    rec_rows = []
    pr = r["hr"]["primary"]["models"]
    for rec in dc["per_record"]:
        rec_rows.append([rec, *[f(pr[k]["per_record"][rec]["mae"]) for k in pr]])
    L += ["### 3.2 Per-record MAE (bpm), primary analysis", "", table(["Record", *pr.keys()], rec_rows), ""]
    s2 = r["sensitivity"]["S2"]
    L += [f"### 3.3 S2: reference-quality screen (windows with any RR < {s2['rr_min_s']} s or > {s2['rr_max_s']} s removed from training and test; "
          f"{s2['windows_removed']} windows removed)", ""]
    L += hr_section(r["hr"]["S2_rr_screened"], "S2 results", participants)[2:]
    L += ["### 3.4 Bland–Altman statistics (descriptive only)", "",
          "Bias ± 1.96 SD of the window errors per participant. Windows overlap and are autocorrelated, so these are **not** valid limits of agreement. No plot is produced (no plotting dependency is installed).", "",
          table(["Model", *participants],
                [[k, *[f"{f(mod['per_participant'][p]['bias'], 1)} ({f(mod['per_participant'][p]['loa_low'], 1)}, {f(mod['per_participant'][p]['loa_high'], 1)})"
                       for p in participants]] for k, mod in pr.items()]), ""]

    L += ["## 4. Baseline comparison: does PPG add information beyond motion?", "",
          "**Reading rule (fixed before any result was computed):** for A4 − A5 and A3 − A5, a 95% participant-bootstrap interval "
          "entirely below 0 is read as evidence that the PPG features carry HR information beyond the accelerometer features "
          "*in this dataset*. An interval that includes 0 is read as *no evidence either way at n = 8*, not as evidence of no effect. "
          "An interval entirely above 0 means the PPG-based model did worse.", ""]
    rows = []
    for c in r["hr"]["primary"]["comparisons"]:
        rows.append([f"{c['a']} − {c['b']}", c["window_set"], ci(c["aggregate"]), f"{c['participants_a_lower']} / {len(c['per_participant'])}",
                     " ".join(f"{p}:{f(v, 1)}" for p, v in c["per_participant"].items())])
    L += ["**Task A, primary analysis** (MAE difference, bpm; negative = first model lower error):", "",
          table(["Difference", "Windows", "Mean [95% CI]", "Participants first lower", "Per participant"], rows), ""]
    rows = []
    for c in r["hr"]["S2_rr_screened"]["comparisons"]:
        rows.append([f"{c['a']} − {c['b']}", c["window_set"], ci(c["aggregate"]), f"{c['participants_a_lower']} / {len(c['per_participant'])}"])
    L += ["**Task A, S2 screened** (same differences):", "", table(["Difference", "Windows", "Mean [95% CI]", "Participants first lower"], rows), ""]

    L += ["## 5. Activity classification (Task B)", "",
          "Labels are **per record** (every window inherits its record's protocol label); there is no per-window activity truth. "
          "Folds whose test participant has only one activity (s4: run; s9: walk) have macro-F1 = n/a.", ""]
    for key, title in (("primary_3class", "5.1 Primary: 3 classes (walk / run / cycle; both bike levels merged)"),
                       ("secondary_4class", "5.2 Secondary: 4 classes (only 3 participants can supply high-bike test data)")):
        b = r["activity"][key]
        cls = b["classes"]
        L += [f"### {title}", "", f"Windows: {b['n_windows']}.", "",
              table(["ID", "Model", "Pooled accuracy", "Balanced accuracy", "Macro-F1", "Mean fold accuracy [95% CI]",
                     "Record-level accuracy (19 records)"],
                    [[k, ACT_MODEL_NAMES[k], f(m["pooled"]["accuracy"], 3), f(m["pooled"]["balanced_accuracy"], 3),
                      f(m["pooled"]["macro_f1"], 3), ci(m["fold_accuracy_aggregate"], 3), f(m["record_level"]["summary"]["accuracy"], 3)]
                     for k, m in b["models"].items()]), ""]
        for k, m in b["models"].items():
            L += [f"**{k} pooled window confusion matrix** (rows = true, columns = predicted):", "",
                  table(["true \\ pred", *cls], [[c, *m["confusion_matrix"][i]] for i, c in enumerate(cls)]), ""]
        for k in ("B1", "B2"):
            m = b["models"][k]
            L += [f"**{k} per-class metrics (pooled)**", "",
                  table(["Class", "Support", "Predicted", "Precision", "Recall", "F1"],
                        [[c, s["support"], s["predicted"], f(s["precision"], 3), f(s["recall"], 3), f(s["f1"], 3)]
                         for c, s in m["pooled"]["per_class"].items()]), "",
                  f"**{k} record-level confusion matrix** (majority vote of windows):", "",
                  table(["true \\ pred", *cls], [[c, *m["record_level"]["confusion_matrix"][i]] for i, c in enumerate(cls)]), ""]
        rows = []
        for p in participants:
            rows.append([p, "/".join(b["models"]["B1"]["per_fold"][p]["classes_present"]), b["models"]["B1"]["per_fold"][p]["n"],
                         *[f"{f(b['models'][k]['per_fold'][p]['accuracy'], 3)} / {f(b['models'][k]['per_fold'][p]['macro_f1'], 3)}" for k in b["models"]]])
        L += ["**Per participant (test fold): accuracy / macro-F1** (macro-F1 over the classes present in that fold; n/a = single class)", "",
              table(["Participant", "Classes present", "Windows", *[f"{k}" for k in b["models"]]], rows), ""]
        conv = [f"{fo['test']}: {'converged' if fo['converged'] else 'NOT converged'} ({fo['n_iter']} it)"
                for k in ("B1", "B2") for fo in b["models"][k]["folds"]]
        L += [f"Optimizer status (B1 then B2, per fold): {'; '.join(conv)}.", ""]
        L += [table(["Difference", "Mean fold-accuracy difference [95% CI]", "Participants first higher"],
                    [[f"{c['a']} − {c['b']}", ci(c["aggregate"], 3), f"{c['participants_a_higher']} / {len(c['per_participant'])}"]
                     for c in b["comparisons"]]), ""]

    L += ["## 6. Failure cases (primary HR analysis)", "",
          table(["Model", "Worst participant (MAE)", "Worst record (MAE)", "Rank of M5 failure records (of 19, 1 = worst)"],
                [[k, f"{v['worst_participant']} ({f(v['worst_participant_mae'])})", f"{v['worst_record']} ({f(v['worst_record_mae'])})",
                  ", ".join(f"{rec} #{x['rank_of_19']}" for rec, x in v["m5_failure_record_ranks"].items())]
                 for k, v in r["hr_failure_cases"].items()]), "",
          "**Top 10% windows by absolute error**, compared with all scored windows (accelerometer magnitude in header units, uncalibrated, descriptive only):", "",
          table(["Model", "n", "|error| ≥ bpm", "walk/run/cycle (top)", "walk/run/cycle (all)", "Median ref HR top / all",
                 "Median accel magnitude top / all"],
                [[k, t["n"], f(t["abs_error_threshold_bpm"], 1),
                  "/".join(str(t["activity_counts"][a]) for a in ("walk", "run", "cycle")),
                  "/".join(str(t["all_windows_activity_counts"][a]) for a in ("walk", "run", "cycle")),
                  f"{f(t['median_ref_hr'], 1)} / {f(t['all_windows_median_ref_hr'], 1)}",
                  f"{f(t['median_accel_mag'], 2)} / {f(t['all_windows_median_accel_mag'], 2)}"]
                 for k, t in ((k, v["top_error_windows"]) for k, v in r["hr_failure_cases"].items())]), ""]

    d = r["post_hoc_a2_ratio_diagnostic"]
    L += ["**Post-hoc A2 diagnostic** (" + d["label"] + "): fraction of windows whose A2 / reference ratio is near 1×, 2× or 0.5×.", "",
          table(["Activity", "Windows", "≈1× (0.9–1.1)", "≈2× (1.8–2.2)", "≈0.5× (0.45–0.55)"],
                [[a, v["n"], pct(v["near_1x"]), pct(v["near_2x"]), pct(v["near_0.5x"])] for a, v in d["per_activity"].items()]), ""]

    L += ["## 7. Dataset limitations", "",
          "- **n = 8 participants.** Every interval above is a coarse participant bootstrap and can be unstable; one participant can move a mean.",
          "- **Non-astronaut population**, terrestrial 1 g laboratory exercise. Nothing here transfers to astronauts or spaceflight.",
          "- **Activity labels are per record** and the files do not mark exercise onset (subjects started from rest; S1 omitted, see §2).",
          "- **Activity is confounded with participant and intensity** (self-selected speeds 2–10 km/h; s6 speed/level unknown).",
          "- **Preprocessing differs by activity in the released data:** the dataset documentation states the cycling PPG traces were "
          "low-pass filtered (15 Hz) before release, while walk/run PPG is raw. PPG-based activity results (B2) could partly reflect that, "
          "although the PPG features used here are restricted to 0.5–4 Hz.",
          "- **Wrist timestamp anomalies:** the wrist clock channel is not used; the uniform 256 Hz index is the time base.",
          "- **Uncalibrated amplitudes:** no raw-amplitude features are used.",
          "- **PPG motion artifacts** dominate several records (see §6).",
          "- **No stress, clinical or outcome labels exist;** no such task was attempted.",
          "- **Reference quality:** hand-marked beats are used as given; S2 shows the effect of screening implausible RR intervals.",
          "- Bland–Altman limits are descriptive only (autocorrelated windows).", "",
          "## 8. Output files", "",
          "`results.json` (all metrics), `windows.csv`, `features.csv`, `hr_predictions_primary.csv`, `hr_predictions_S2_rr_screened.csv`, "
          "`hr_per_participant.csv`, `hr_per_record.csv`, `hr_aggregate.csv`, `activity_predictions_primary_3class.csv`, "
          "`activity_predictions_secondary_4class.csv`, `activity_per_fold.csv`, `activity_confusion.csv`, `activity_class_metrics.csv`, `report.md`.", ""]
    return "\n".join(L)
