"""Signal registry: the single source of truth for every channel the twin panel shows.

Each channel has exactly one status, a provenance/source description, and a lane.
The registry holds NO measurement values: lab values come only from the verified
OSD-575 file at run time, and every other channel is listed without any value.

Statuses
    MEASURED_LAB_SAMPLE     real values from a verified laboratory sample file
                            (sparse timepoints, not continuous sensing)
    RECORDED_NON_ASTRONAUT  real recordings from a non-astronaut study (none enabled yet)
    SIMULATED               synthetic values for UI demonstration (none defined; off)
    UNAVAILABLE             no accessible, verified source; shown without any value

Lanes keep NASA laboratory data separate from wearable-model (WESAD) data:
    "nasa-lab"        OSD-575 serum analytes
    "wearable-model"  WESAD channels, for a later, gated methods demonstration
    "simulated"       deterministic demo playback (sim_wearable.py); SIMULATED only
    "recorded"        PhysioNet Wrist PPG During Exercise (non-astronaut); RECORDED only
    "unavailable"     hardware/measures with no public source identified
This module performs no file or network access.
"""

from __future__ import annotations

from collections import Counter
from dataclasses import dataclass

from . import sim_wearable
from .osdr_cmp import OSDR_CMP_PAIRS

MEASURED_LAB_SAMPLE = "MEASURED-LAB-SAMPLE"
RECORDED_NON_ASTRONAUT = "RECORDED-NON-ASTRONAUT"
SIMULATED = "SIMULATED"
UNAVAILABLE = "UNAVAILABLE"
STATUSES = (MEASURED_LAB_SAMPLE, RECORDED_NON_ASTRONAUT, SIMULATED, UNAVAILABLE)

STATUS_TEXT = {
    MEASURED_LAB_SAMPLE: "Measured · lab sample",
    RECORDED_NON_ASTRONAUT: "Recorded · non-astronaut",
    SIMULATED: "Simulated",
    UNAVAILABLE: "Unavailable",
}
STATUS_MEANING = {
    MEASURED_LAB_SAMPLE: "Real values from a SHA-256-verified laboratory file; sparse timepoints, not continuous sensing.",
    RECORDED_NON_ASTRONAUT: "Real recordings from a terrestrial non-astronaut study (PhysioNet), SHA-256-verified; kept separate from astronaut data.",
    SIMULATED: "Generated by a fixed formula for the demo playback only. Never astronaut data; never merged with NASA lab data.",
    UNAVAILABLE: "No accessible, verified data source. No values are shown or generated.",
}

LANE_NASA_LAB = "nasa-lab"
LANE_WEARABLE_MODEL = "wearable-model"
LANE_UNAVAILABLE = "unavailable"
LANE_SIMULATED = "simulated"
LANE_RECORDED = "recorded"

# Neutral body-region layout. Laboratory analytes are grouped by SAMPLE TYPE, never by organ.
REGION_BLOOD = "Blood serum (laboratory sample)"
REGION_HEAD = "Head"
REGION_CHEST = "Chest / torso"
REGION_WRIST = "Wrist"
REGION_WHOLE_BODY = "Whole body"
REGION_CABIN = "Cabin environment"
REGIONS = (REGION_HEAD, REGION_CHEST, REGION_WRIST, REGION_WHOLE_BODY, REGION_BLOOD, REGION_CABIN)

OSD575_TIMEPOINTS = "L-92, L-44, L-3 (pre-flight); R+1, R+45, R+82, R+194 (post-flight)"
WESAD_PENDING = ("Pending the WESAD gate: terms of use, label codes, file format and checksums are not "
                 "verified. Not downloaded, not redistributed, not used for training.")
NO_PUBLIC_SOURCE = "No public data source identified (see docs/DATA-SOURCE-INVENTORY.md)."


@dataclass(frozen=True)
class Channel:
    channel_id: str
    label: str
    region: str
    status: str            # exactly one of STATUSES
    lane: str
    source: str            # provenance / where the data would come from
    sampling: str          # e.g. sparse timepoint labels, native sensor rate, or "none"
    unit: str = ""         # exact unit string for lab channels; empty when there is no data
    note: str = ""         # reason a channel is unavailable, or a limitation


def _osd575_channels() -> list[Channel]:
    source = ("NASA OSDR OSD-575 serum Comprehensive Metabolic Panel (SpaceX Inspiration4, 4 crew); "
              "file LSDS-8_Comprehensive_Metabolic_Panel_CMP.upload_SUBMITTED.csv, SHA-256-verified on load. "
              "No licence stated in the OSDR record; downloaded on demand, not bundled.")
    return [
        Channel(channel_id=f"osd575:{analyte}", label=analyte, region=REGION_BLOOD,
                status=MEASURED_LAB_SAMPLE, lane=LANE_NASA_LAB, source=source,
                sampling=f"Sparse blood draws, collection labels only (no clock times): {OSD575_TIMEPOINTS}",
                unit=unit,
                note="Laboratory value as published; unit not converted; descriptive use only.")
        for analyte, unit in sorted(OSDR_CMP_PAIRS)
    ]


