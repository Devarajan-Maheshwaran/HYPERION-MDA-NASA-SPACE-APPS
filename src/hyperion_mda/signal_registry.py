CHANNELS: tuple[Channel, ...] = tuple(_osd575_channels() + _wesad_channels() + _unavailable_channels()
                                      + _simulated_channels() + _recorded_channels())


def channels_in(region: str | None = None) -> list[Channel]:
    return [c for c in CHANNELS if region is None or c.region == region]


def status_counts() -> Counter:
    return Counter(c.status for c in CHANNELS)


def nasa_lab_channel_for(analyte: str, unit: str) -> Channel | None:
    """The registry channel for an OSD-575 record (exact analyte and unit match only)."""
    return next((c for c in CHANNELS if c.lane == LANE_NASA_LAB and c.label == analyte and c.unit == unit), None)


def validate_registry(channels: tuple[Channel, ...] = CHANNELS) -> list[str]:
    """Structural rules; returns a list of problems (empty when the registry is consistent)."""
    problems: list[str] = []
    ids = Counter(c.channel_id for c in channels)
    problems += [f"duplicate channel id {cid}" for cid, n in ids.items() if n > 1]
    for c in channels:
        if c.status not in STATUSES:
            problems.append(f"{c.channel_id}: invalid status {c.status!r}")
        if c.region not in REGIONS:
            problems.append(f"{c.channel_id}: unknown region {c.region!r}")
        if not c.source.strip():
            problems.append(f"{c.channel_id}: missing source description")
        if c.lane == LANE_NASA_LAB and c.status != MEASURED_LAB_SAMPLE:
            problems.append(f"{c.channel_id}: NASA lab channel must be {MEASURED_LAB_SAMPLE}")
        if c.lane == LANE_NASA_LAB and c.region != REGION_BLOOD:
            problems.append(f"{c.channel_id}: lab analytes are grouped by sample type, not organ")
        if c.lane != LANE_NASA_LAB and c.status == MEASURED_LAB_SAMPLE:
            problems.append(f"{c.channel_id}: only NASA lab channels may be {MEASURED_LAB_SAMPLE}")
        if c.lane == LANE_WEARABLE_MODEL and c.status not in (UNAVAILABLE, RECORDED_NON_ASTRONAUT):
            problems.append(f"{c.channel_id}: wearable-model channels are never astronaut measurements")
        if (c.lane == LANE_RECORDED) != (c.status == RECORDED_NON_ASTRONAUT):
            problems.append(f"{c.channel_id}: RECORDED status and the recorded lane must go together")
        if (c.lane == LANE_SIMULATED) != (c.status == SIMULATED):
            problems.append(f"{c.channel_id}: SIMULATED status and the simulated lane must go together")
        if c.status == UNAVAILABLE and c.unit:
            problems.append(f"{c.channel_id}: unavailable channel must not carry a unit")
    return problems
