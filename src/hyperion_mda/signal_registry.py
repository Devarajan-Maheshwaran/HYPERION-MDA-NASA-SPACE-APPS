def _simulated_channels() -> list[Channel]:
    region = {"sim:hr-like": REGION_CHEST, "sim:skin-temp-like": REGION_WRIST, "sim:accel-like": REGION_WRIST}
    src = ("Deterministic demo generator (sim_wearable.py) replayed through the SimulatedPlaybackAdapter. "
           "Not measured, not from any device, not astronaut data.")
    return [Channel(channel_id=c.channel_id, label=c.label, region=region[c.channel_id], status=SIMULATED,
                    lane=LANE_SIMULATED, source=src, sampling=f"{c.rate_hz:g} Hz simulated playback",
                    note="Shown only in the Simulated wearable window; never merged with NASA records.")
            for c in sim_wearable.CHANNELS]


