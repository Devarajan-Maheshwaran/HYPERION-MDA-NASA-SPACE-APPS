"""SIMULATED wearable playback window. Every value is generated; nothing is measured.

Uses only the adapter boundary (`adapters.py`). It never reads or writes the NASA
lab-data records shown in the main window.
"""

from __future__ import annotations

import tkinter as tk
from tkinter import messagebox, ttk

from .adapters import AdapterError, PlaybackSession, SimulatedPlaybackAdapter, WearableAdapter

SIM_BANNER = ("SIMULATED WEARABLE PLAYBACK · every value is generated by a fixed formula · not measured, "
              "not from a device, not astronaut data · never merged with NASA lab data · no health meaning")
TICK_MS = 250
LINE = "#7a5a2b"     # same neutral "simulated" brown as the SIMULATED badge
GRID = "#e6eaee"
MUTED = "#66727e"


class PlaybackWindow(tk.Toplevel):
    def __init__(self, master: tk.Misc, adapter: WearableAdapter | None = None, *, banner: str = SIM_BANNER,
                 title: str = "HYPERION-MDA · SIMULATED wearable playback", window_s: float = 60.0,
                 step_s: float = 1.0, banner_bg: str = "#5a4413", line: str = LINE) -> None:
        super().__init__(master)
        self.title(title)
        self.geometry("1000x680")
        self.minsize(760, 520)
        self.configure(bg="#101923")
        self.banner_text, self.banner_bg, self.line = banner, banner_bg, line
        self.adapter = adapter or SimulatedPlaybackAdapter()
        self.session = PlaybackSession(self.adapter, window_s=window_s, step_s=step_s)
        self._job: str | None = None
        self._build()
        self.redraw()

    def _build(self) -> None:
        self.banner = tk.Label(self, text=self.banner_text, bg=self.banner_bg, fg="#fff0c8", font=("Segoe UI", 9, "bold"),
                               padx=12, pady=9, justify="center")
        self.banner.pack(side="top", fill="x", padx=16, pady=(12, 6))
        self.banner.bind("<Configure>", lambda e: self.banner.configure(wraplength=max(300, e.width - 30)))

        info = ttk.Frame(self, padding=(16, 0))
        info.pack(fill="x")
        real = "yes" if self.adapter.is_real_device else "no (no device is connected)"
        ttk.Label(info, text=f"Source adapter: {self.adapter.name} · provenance: {self.adapter.provenance} "
                             f"· real device: {real}").pack(anchor="w")

        controls = ttk.Frame(self, padding=(16, 8))
        controls.pack(fill="x")
        ttk.Button(controls, text="Start", command=self.start).pack(side="left")
        ttk.Button(controls, text="Pause", command=self.pause).pack(side="left", padx=6)
        ttk.Button(controls, text="Reset", command=self.reset).pack(side="left")
        ttk.Label(controls, text="  Time (s):").pack(side="left")
        self.scale = ttk.Scale(controls, from_=0, to=self.adapter.duration_s(), orient="horizontal",
                               command=self._on_scale)
        self.scale.pack(side="left", fill="x", expand=True, padx=6)
        self.position_text = tk.StringVar()
        ttk.Label(controls, textvariable=self.position_text, width=54).pack(side="left")

        self.canvas = tk.Canvas(self, bg="#ffffff", highlightthickness=1, highlightbackground="#c9d1d9")
        self.canvas.pack(fill="both", expand=True, padx=16, pady=(0, 14))
        self.canvas.bind("<Configure>", lambda _e: self.redraw())

    # ----- controls --------------------------------------------------------------------

    def start(self) -> None:
        self.session.start()
        self._schedule()
        self.redraw()

    def pause(self) -> None:
        self.session.pause()
        self.redraw()

    def reset(self) -> None:
        self.session.reset()
        self.redraw()

    def seek(self, t_s) -> None:
        try:
            self.session.seek(t_s)
        except AdapterError as exc:
            messagebox.showerror("Playback", str(exc), parent=self)
            return
        self.redraw()

    def _on_scale(self, value: str) -> None:
        if abs(float(value) - self.session.position_s) >= 0.5:  # ignore echoes of our own updates
            self.seek(value)

    def _schedule(self) -> None:
        if self._job is None and self.session.running:
            self._job = self.after(TICK_MS, self._tick)

    def _tick(self) -> None:
        self._job = None
        if self.session.tick():
            self.redraw()
        self._schedule()

    def destroy(self) -> None:
        if self._job is not None:
            self.after_cancel(self._job)
            self._job = None
        super().destroy()

    # ----- drawing ---------------------------------------------------------------------

    def redraw(self) -> None:
        s = self.session
        state = "playing" if s.running else ("finished" if s.finished else "paused")
        self.position_text.set(f"t = {s.position_s:.0f} s of {self.adapter.duration_s():.0f} s · {state} · "
                               f"{self.adapter.provenance}")
        self.scale.set(s.position_s)
        c = self.canvas
        c.delete("all")
        try:
            samples = s.visible()
        except AdapterError as exc:
            s.pause()
            c.create_text(20, 20, anchor="nw", text=f"Playback stopped: {exc}", fill="#7a2b2b")
            messagebox.showerror("Playback input error", str(exc), parent=self)
            return
        width, height = max(c.winfo_width(), 300), max(c.winfo_height(), 200)
        specs = self.adapter.channels()
        strip_h = height / len(specs)
        t1 = max(s.position_s, s.window_s)
        t0 = t1 - s.window_s
        for i, spec in enumerate(specs):
            top, bottom = i * strip_h + 26, (i + 1) * strip_h - 18
            left, right = 70, width - 20
            pts = [x for x in samples if x.channel_id == spec.channel_id]
            latest = f"{pts[-1].value:.2f}" if pts else "—"
            c.create_text(left, top - 18, anchor="nw", font=("Segoe UI", 9, "bold"), fill=self.line,
                          text=f"{spec.label} · unit: {spec.unit} · latest {latest}", tags=("strip_title",))
            c.create_rectangle(left, top, right, bottom, outline=GRID)
            if len(pts) > 1500:  # decimate for drawing only; the samples themselves are unchanged
                pts = pts[::-(-len(pts) // 1500)]
            if len(pts) >= 2:
                lo, hi = min(p.value for p in pts), max(p.value for p in pts)
                if hi - lo < 1e-9:
                    lo, hi = lo - 1, hi + 1
                xy = []
                for p in pts:
                    xy += [left + (p.t_s - t0) / (t1 - t0) * (right - left),
                           bottom - (p.value - lo) / (hi - lo) * (bottom - top)]
                c.create_line(*xy, fill=self.line, width=1.2, tags=("sim_line",))
                c.create_text(left - 6, top, anchor="ne", text=f"{hi:.1f}", font=("Segoe UI", 8), fill=MUTED)
                c.create_text(left - 6, bottom, anchor="se", text=f"{lo:.1f}", font=("Segoe UI", 8), fill=MUTED)
            c.create_text(left, bottom + 2, anchor="nw", font=("Segoe UI", 8), fill=MUTED,
                          text=f"{t0:.0f} s")
            c.create_text(right, bottom + 2, anchor="ne", font=("Segoe UI", 8), fill=MUTED,
                          text=f"{t1:.0f} s ({'simulated' if self.adapter.provenance == 'SIMULATED' else 'record'} time)")
